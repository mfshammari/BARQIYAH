-- 0025 — تقسيمات المدعوين
--
-- صاحب المناسبة يرتّب قائمته في تقسيمات (العائلة، الجيران، الأصدقاء…)
-- ولكل تقسيمة فرع اختياري (المهيني ← الرياض / حائل…). نصّان حرّان على
-- صفّ المدعو نفسه: لا جدول مرجعي، والتقسيمة توجد بوجود مدعو يحملها.
-- العمودان اختياريان — المدعوون السابقون يبقون بلا تقسيمة.
-- ============================================================

alter table public.guests
  add column if not exists section text,
  add column if not exists branch  text;

create index if not exists guests_section_idx
  on public.guests (event_id, section);
